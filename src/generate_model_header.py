'''
File:
generate_model_header.py

Description:
Part 3 -- export the shipped model as a C header for the microcontroller.

The model is exactly what the classifier is allowed to read: one uint8
table per class (GRID_N x GRID_N bytes) and the training scaling bounds
(a min and max per feature, as 4-byte floats). This writes both into
model.h as const arrays, in the layout of the instructor's sample
(GRID_N, NUM_CLASSES, CLASS_TABLE, SCALE_BOUNDS, CLASS_NAMES,
REJECT_TAU), so the firmware needs no file system and the model costs
K * GRID_N**2 + 16 bytes of flash, the figure from
discretize_surfaces.py. The class names are a few bytes more, and the
#defines cost nothing.

DBSCAN only numbers its clusters, so CLASS_NAMES (in pipeline_common) is
a hand-made mapping, read off each cluster's centroid (the labels are
never used).

Note:
- Run from src/ (paths are relative to it), after kde_class_contours.py.
- Reads outputs/<DATASET>/surfaces.npz; the bounds are recomputed from
  the training split, the same way every other stage gets them.
- Writes outputs/<DATASET>/model.h; in sensor mode, also a copy into each
  ESP32 sketch folder (src/classify_serial/, src/classify_led/).

___________________________________________________
Author      Date                Comment
Gib M.      Oct. 15th, 2026     rev 1
'''
import math
import os

import numpy as np
from pipeline_common import (load_split_scaled, scale_features, quantize,
                             cell_of, DATASET, GRID_N, REJECT_TAU,
                             CLASS_NAMES, SURFACES_NPZ, OUT_DIR)

MODEL_H = OUT_DIR + "model.h"
# The ESP32 sketches each need their own copy: the Arduino IDE only
# compiles files inside the sketch's folder.
FIRMWARE_DIRS = ["classify_serial/", "classify_led/"]

data = load_split_scaled()
lo, hi = data["bounds"]  # training bounds, in transformed (log1p) units
surfaces = np.load(SURFACES_NPZ)
classes = sorted(int(k[1:]) for k in surfaces.files)  # keys are "c0", "c1"...
K = len(classes)
assert classes == list(range(len(CLASS_NAMES))), "CLASS_NAMES out of date"

# --- The shipped bytes -------------------------------------------------------
tables = np.stack([quantize(surfaces[f"c{c}"]) for c in classes])
# Laid out {xmin, xmax, ymin, ymax} as in the sample. float32 because that
# is what the firmware stores; 4 floats x 4 bytes = 16 bytes.
bounds32 = np.array([lo[0], hi[0], lo[1], hi[1]], dtype=np.float32)

model_bytes = tables.nbytes + bounds32.nbytes
assert tables.dtype == np.uint8 and tables.shape == (K, GRID_N, GRID_N)
assert model_bytes == K * GRID_N**2 + 16, model_bytes

# The firmware tests the raw byte instead of dequantizing it:
# byte / 255 < tau  <=>  byte < tau * 255  <=>  byte < ceil(tau * 255).
reject_q = math.ceil(REJECT_TAU * 255)

# --- Check float32 bounds land every point in the same cell ------------------
# Rounding the bounds to float32 could, in principle, push a point across a
# cell edge. Re-scale the raw-transformed points both ways and compare.
f32_bounds = (bounds32[[0, 2]].astype(float), bounds32[[1, 3]].astype(float))
moved = 0
for split in ("train", "val", "test"):
    raw = data[split] * (hi - lo) + lo  # undo the float64 scaling
    rescaled, _ = scale_features(raw, f32_bounds)
    moved += sum(cell_of(p) != cell_of(q)
                 for p, q in zip(data[split], rescaled))


# --- Write model.h -----------------------------------------------------------
def c_float(v):
    """A float32 literal that reads back to the same value ('.9g' is
    enough digits to round-trip any float32)."""
    s = f"{float(v):.9g}"
    return s + ("f" if any(ch in s for ch in ".e") else ".0f")


lines = [
    f"/* model.h -- generated by generate_model_header.py from",
    f" * outputs/{DATASET}/surfaces.npz. Do not edit by hand.",
    f" * Model: {K} * {GRID_N}^2 table bytes + 16 bound bytes"
    f" = {model_bytes} bytes. */",
    "#ifndef MODEL_H",
    "#define MODEL_H",
    "",
    "#include <stdint.h>",
    "#if defined(__AVR__)",
    "#include <avr/pgmspace.h>  /* PROGMEM; read tables with pgm_read_byte */",
    "#elif !defined(PROGMEM)",
    "#define PROGMEM            /* ESP32 / PC: const data stays in flash */",
    "#endif",
    "",
    f"#define GRID_N {GRID_N}",
    f"#define NUM_CLASSES {K}",
    "",
    "/* CLASS_TABLE[class][row][col]: row follows y (feature 2), col x",
    " * (feature 1). Each table is that class's KDE, peak scaled to 255. */",
    "const uint8_t CLASS_TABLE[NUM_CLASSES][GRID_N][GRID_N] PROGMEM = {",
]
for c, table in zip(classes, tables):
    lines.append(f"    {{ /* {c}: {CLASS_NAMES[c]} */")
    for row in table:
        lines.append("        {" + ", ".join(f"{b:3d}" for b in row) + "},")
    lines.append("    },")
lines += [
    "};",
    "",
    "/* Training bounds. x = (x_raw - xmin) / (xmax - xmin), likewise y;",
    "   col = (int)(x * GRID_N), row = (int)(y * GRID_N), clipped to",
    "   [0, GRID_N - 1]."
    + ("\n   Bounds are in log units: apply log1p to both raw readings"
       " first." if DATASET == "sensor" else "") + " */",
    "const float SCALE_BOUNDS[4] = {"
    + ", ".join(c_float(v) for v in bounds32) + "};"
    "  // xmin, xmax, ymin, ymax",
    "",
    "const char* CLASS_NAMES[NUM_CLASSES] = {"
    + ", ".join(f'"{CLASS_NAMES[c]}"' for c in classes) + "};",
    "",
    "/* Unknown if the winning class's byte / 255 is below this,",
    f"   i.e. if the byte is below {reject_q}. */",
    f"#define REJECT_TAU {c_float(REJECT_TAU)}",
    "",
    "#endif /* MODEL_H */",
    "",
]

# The firmware reads the real sensor, so only the sensor model goes there.
targets = [MODEL_H] + ([d + "model.h" for d in FIRMWARE_DIRS]
                       if DATASET == "sensor" else [])
for path in targets:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", newline="\n") as f:
        f.write("\n".join(lines))

print(f"{K} classes x {GRID_N}x{GRID_N} bytes + 16 bytes of bounds "
      f"= {model_bytes} bytes")
print(f"reject if winning byte < {reject_q} (tau = {REJECT_TAU})")
print(f"points moved to another cell by float32 bounds: {moved}")
print("wrote " + ", ".join(targets))
